"""Animation coverage report (directive section 12) -> docs/qa/animation_coverage.md.

Reads assets/manifest.json, data/characters.json, data/guild.json, data/weapons.json and
data/weapon_styles.json; lists per playable hero the real animation states, frames, size,
directions and what each weapon style needs that the sheets do not provide.
"""
from __future__ import annotations

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
NEEDED_BODY = {  # body states a fully hand-animated hero would have per style family
    "magic": ["cast"], "melee": ["attack_swing", "attack_thrust"], "ranged": ["attack_draw"],
}
FAMILY = {"staff": "magic", "wand": "magic", "orb": "magic", "sword": "melee", "dagger": "melee",
          "spear": "melee", "heavy": "melee", "bow": "ranged", "gun": "ranged"}


def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def main() -> None:
    m = load("assets/manifest.json")["sprites"]
    chars = {c["id"]: c for c in load("data/characters.json")["characters"]}
    roster = load("data/guild.json")["roster"]
    weapons = {w["id"]: w for w in load("data/weapons.json")["weapons"]}
    styles = load("data/weapon_styles.json")["styles"]
    classes = {c["id"]: c for c in load("data/classes.json")["classes"]}
    out = ["# Animation coverage report", "",
           "Generated by `python tools/anim_coverage.py`. Real = frames in the sprite sheet;",
           "procedural = motion done in code (scripts/combat/weapon.gd) on top of real frames.", "",
           "## Heroes", "",
           "| hero | sheet | frame | density | directions | states (frames) | source |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for hid in roster:
        s = m[chars[hid]["sprite"]]
        st = ", ".join(f"{k} ({v['frames']})" for k, v in s["anims"].items())
        out.append(f"| {chars[hid]['name']} ({hid}) | `{s['path'].replace('res://', '')}` | {s['frame_w']}x{s['frame_h']} | "
                   f"{s['density']} | right (left = horizontal flip) | {st} | {s.get('source', '')} |")
    out += ["", "No hero sheet contains attack frames. idle/dash/skill/hurt/death are cut-out animations of the",
            "single reference pose; run is the user's 8-frame sheet (5 heroes).", "",
            "## Weapon styles", "",
            "| style | weapons | windup / active / recover (s) | weapon motion | body state used | weapon frames | missing for full quality |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for sid, p in styles.items():
        ws = [w for w, d in weapons.items() if d.get("style") == sid]
        wf = []
        for w in ws:
            a = m.get(f"weapon_{w}", {}).get("anims", {})
            wf.append(f"{w}: " + "/".join(f"{k}({v['frames']})" for k, v in a.items()))
        body = p["body"] or "idle/run (unchanged)"
        missing = ", ".join(f"hero `{x}` frames" for x in NEEDED_BODY[FAMILY[sid]])
        out.append(f"| {sid} | {', '.join(ws)} | {p['windup']} / {p['active']} / {p['recover']} | {p['motion']} (procedural) | "
                   f"{body} | {'; '.join(wf)} | {missing} |")
    out += ["", "## Class weapon rules", ""]
    for cid, c in classes.items():
        if "weapons" in c:
            out.append(f"- {c['name']}: {', '.join(c['weapons'])}")
    out += ["", "## Known visual limitations", "",
            "- The `skill` body animation used as the casting pose is the reference pose with sparkles; a",
            "  dedicated raise-staff cast sheet per hero is still needed.",
            "- Melee swings move the weapon sprite around the hand; the body does not swing (no attack frames).",
            "- Only the Thornbow has dedicated draw/release frames; other weapons are single frames.",
            "- Heroes face right only; left is a horizontal flip (the weapon is flipped vertically around the aim axis)."]
    path = os.path.join(ROOT, "docs", "qa", "animation_coverage.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
