def build(png_path: str, fnt_path: str, png_name: str) -> None:
    cell_w, cell_h = 7, 10
    chars = sorted(G.keys(), key=ord)
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cell_w, rows * cell_h), (0, 0, 0, 0))
    p = img.load()
    lines = [
        'info face="Hexvault" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight=10 base=8 scaleW={img.width} scaleH={img.height} pages=1 packed=0",
        f'page id=0 file="{png_name}"',
        f"chars count={len(chars)}",
    ]
    for i, ch in enumerate(chars):
        rows_ = G[ch]
        assert len(rows_) == 8, f"glyph {ch!r} needs 8 rows"
        w = len(rows_[0])
        assert all(len(r) == w for r in rows_), f"glyph {ch!r} ragged"
        cx, cy = (i % cols) * cell_w, (i // cols) * cell_h
        for y, row in enumerate(rows_):
            for x, v in enumerate(row):
                if v == "#":
                    p[cx + x, cy + y] = (255, 255, 255, 255)
        adv = w + 1 if ch != " " else 4
        lines.append(f"char id={ord(ch)} x={cx} y={cy} width={w} height=8 xoffset=0 yoffset=1 xadvance={adv} page=0 chnl=15")
    import os
    same = False
    if os.path.exists(png_path):
        with Image.open(png_path) as old:
            same = old.size == img.size and old.convert("RGBA").tobytes() == img.tobytes()
    if not same:  # pixel-identical files are kept (PNG bytes vary by Pillow version)
        img.save(png_path)
    with open(fnt_path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
