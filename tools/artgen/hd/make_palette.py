"""Regenerate hd/palette.py from base colours (run only when changing the palette).

Ramps are built with the hue-shifting ramp() from the vendored pixel-art-studio
skill (.claude/skills/pixel-art-studio): shadows rotate toward blue, highlights
toward yellow, saturation peaks at the midtone. The result is frozen as hex
literals so art generation never depends on that function's exact maths.

Usage: python tools/artgen/hd/make_palette.py
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, ".claude", "skills", "pixel-art-studio", "scripts"))
from pixelstudio import ramp  # noqa: E402

# name: (base colour, hue shift degrees, dark, light)
BASES = {
    "skin_fair": ("#e3a98a", 12, 0.45, 0.55),
    "skin_tan": ("#c07a52", 12, 0.50, 0.55),
    "skin_deep": ("#7e4a33", 12, 0.50, 0.55),
    "hair_brown": ("#7a4a2c", 16, 0.55, 0.55),
    "hair_gold": ("#dca844", 18, 0.50, 0.60),
    "hair_silver": ("#b6b6d2", 10, 0.55, 0.75),
    "hair_red": ("#b8402e", 18, 0.55, 0.55),
    "hair_ink": ("#34314e", 12, 0.55, 0.45),
    "teal": ("#1a9e9a", 18, 0.62, 0.70),
    "amber": ("#e0922a", 20, 0.60, 0.70),
    "crimson": ("#c2304a", 18, 0.60, 0.60),
    "moss": ("#58a33a", 20, 0.60, 0.65),
    "violet": ("#8448cc", 16, 0.60, 0.65),
    "azure": ("#2f6fd6", 16, 0.60, 0.70),
    "steel": ("#7c7ea0", 10, 0.62, 0.80),
    "stone": ("#857c70", 10, 0.60, 0.65),
    "leather": ("#8a5634", 16, 0.60, 0.55),
    "cloth": ("#c4ae84", 14, 0.55, 0.60),
    "bone": ("#ded3b6", 12, 0.50, 0.70),
    "flame": ("#f26a1b", 24, 0.55, 0.85),
    "frost": ("#6cc8ee", 16, 0.55, 0.80),
    "rose": ("#d64f94", 18, 0.60, 0.65),
    "night": ("#3a3152", 10, 0.60, 0.45),
    "slate": ("#4b5268", 10, 0.60, 0.55),
}

STEPS = 6


def main() -> None:
    lines = [
        '"""Hexvault HD master palette (generated by make_palette.py - do not hand edit).',
        "",
        "Each ramp has 6 shades, index 0 = darkest (selout / deep shadow) to",
        "5 = brightest (specular). Plus fixed outline and glow colours.",
        '"""',
        "",
        "RAMPS: dict[str, list[str]] = {",
    ]
    for name, (base, hs, dark, light) in BASES.items():
        r = ramp(base, STEPS, hue_shift=hs, dark=dark, light=light)
        lines.append(f'    "{name}": {r!r},'.replace("'", '"'))
    lines += [
        "}",
        "",
        "# Outline / contact colours and emissive accents (not shaded).",
        "FIXED: dict[str, str] = {",
        '    "ink": "#14101e",',
        '    "void": "#0b0912",',
        '    "white": "#f4f1ff",',
        '    "glow_teal": "#b4fff0",',
        '    "glow_amber": "#ffe28a",',
        '    "glow_violet": "#e3b8ff",',
        '    "glow_red": "#ff9aa2",',
        '    "glow_frost": "#e0f8ff",',
        "}",
        "",
    ]
    out = os.path.join(os.path.dirname(__file__), "palette.py")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
